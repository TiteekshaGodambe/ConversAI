"""
Write the synthetic dataset to one Excel workbook (About, Data Dictionary, ACCOUNT_DIM, ACCOUNT_CYCLE_FACT).

  python tables/export_xlsx.py                 # every column  -> CARD_ACCOUNT_SYNTHETIC_dataset.xlsx (~95 MB, ~2 min)
  python tables/export_xlsx.py --governed      # only the columns the semantic layer uses (+ keys) -> ..._governed.xlsx

Reads warehouse/cards.duckdb (built by tables/build_tables.py). Needs: pip install xlsxwriter
"""
import argparse, csv, datetime as dt, decimal, sys, time
from pathlib import Path
import duckdb, xlsxwriter
ROOT = Path(__file__).resolve().parent.parent; sys.path.insert(0, str(ROOT))
from engine.exports import governed_columns
ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--governed", action="store_true", help="only the governed columns")
ap.add_argument("--out", help="output file (default in the project folder)")
A = ap.parse_args()
OUT = A.out or str(ROOT / ("CARD_ACCOUNT_SYNTHETIC_dataset_governed.xlsx" if A.governed else "CARD_ACCOUNT_SYNTHETIC_dataset.xlsx"))
t0 = time.time()
con = duckdb.connect(str(ROOT / "warehouse" / "cards.duckdb"), read_only=True)
dd = list(csv.DictReader(open(ROOT / "tables" / "data_dictionary.csv", encoding="utf-8")))
split = {r["column"]: r["table"] for r in csv.DictReader(open(ROOT / "tables" / "column_split.csv"))}
gov = governed_columns({"account": ["BILLING_CYCLE_DAY"], "account_cycle": ["BILLING_YEAR_MTH"]})
gov_set = set(gov["account"]) | set(gov["account_cycle"])
keep = {"ACCOUNT_DIM": gov["account"], "ACCOUNT_CYCLE_FACT": gov["account_cycle"]} if A.governed else None
counts = {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in ("ACCOUNT_DIM", "ACCOUNT_CYCLE_FACT")}

wb = xlsxwriter.Workbook(OUT, {"constant_memory": True, "strings_to_numbers": False})
F = lambda **k: wb.add_format({"font_name": "Arial", "font_size": 10, **k})
base, bold = F(), F(bold=True)
title = F(bold=True, font_size=14)
head = F(bold=True, bg_color="#1F3864", font_color="#FFFFFF", border=1, text_wrap=True, valign="top")
wrap = F(text_wrap=True, valign="top")
datef = F(num_format="yyyy-mm-dd")
num2 = F(num_format="#,##0.00")
num0 = F(num_format="0")
num3 = F(num_format="0.000")

# ---- About
ws = wb.add_worksheet("About"); ws.set_column(0, 0, 26, base); ws.set_column(1, 1, 100, wrap)
rows = [
  ("CARD_ACCOUNT_SYNTHETIC dataset", None),
  (None, None),
  ("What this is", ("ONLY THE GOVERNED COLUMNS (the ones the ConversAI semantic layer uses, plus keys). " if A.governed else "") + "The full synthetic credit card dataset used by ConversAI: the original 222-column CARD_ACCOUNT_SYNTHETIC table split into an account table and a monthly cycle table. Synthetic data only - no real customers."),
  ("ACCOUNT_DIM", f"One row per account: {counts['ACCOUNT_DIM']:,} rows x {len(keep['ACCOUNT_DIM']) if keep else 27} columns (account-level attributes that do not change month to month). Key: ACCOUNT_KEY."),
  ("ACCOUNT_CYCLE_FACT", f"One row per account per billing month: {counts['ACCOUNT_CYCLE_FACT']:,} rows x {len(keep['ACCOUNT_CYCLE_FACT']) if keep else 196} columns (Oct 2025 - Sep 2026). Key: ACCOUNT_HISTORY_KEY; joins to ACCOUNT_DIM on ACCOUNT_KEY."),
  ("Data Dictionary", "All 222 original columns with their Oracle type and description, the table each column is in, and whether the ConversAI semantic layer uses it (the governed fields that exports may copy)."),
  ("Rebuild the original", "Join ACCOUNT_CYCLE_FACT to ACCOUNT_DIM on ACCOUNT_KEY: every original row is reproduced exactly (checked by tables/verify_split.py)."),
  ("Source", "Generated by tables/build_tables.py (realistic values: tables/realism.py; rule checks: tables/check_realism.py). Same data as warehouse/cards.duckdb and lake/cards/*.parquet."),
  ("Note on metrics", "Raw columns only. Governed definitions (e.g. 30+ delinquency rate excludes charged-off accounts; paperless = EBILL_IND not blank) live in the semantic layer - compute by hand with care, or ask ConversAI."),
]
for i, (a, b) in enumerate(rows):
    if a: ws.write(i, 0, a, title if i == 0 else bold)
    if b: ws.write(i, 1, b, wrap)

# ---- Data dictionary
ws = wb.add_worksheet("Data Dictionary")
hdr = ["#", "Column Name", "Table", "Oracle Data Type", "Description", "Used by semantic layer"]
widths = [5, 32, 22, 18, 90, 14]
for j, (h, w) in enumerate(zip(hdr, widths)):
    ws.set_column(j, j, w, wrap if j == 4 else base); ws.write(0, j, h, head)
tmap = {"account": "ACCOUNT_DIM", "cycle": "ACCOUNT_CYCLE_FACT", "key": "both (join key)"}
rows_dd = [r for r in dd if not A.governed or r["column"] in gov_set]
for i, r in enumerate(rows_dd, start=1):
    col = r["column"]
    vals = [int(r["n"]), col, tmap.get(split.get(col, ""), split.get(col, "")), r["oracle_type"], r["description"],
            "Y" if col in gov_set else "N"]
    for j, v in enumerate(vals): ws.write(i, j, v, wrap if j == 4 else base)
ws.freeze_panes(1, 2); ws.autofilter(0, 0, len(rows_dd), len(hdr) - 1)

# ---- data sheets
def dump(table):
    desc = [d for d in con.execute(f"DESCRIBE {table}").fetchall() if not keep or d[0] in keep[table]]
    cols_sql = ", ".join(d[0] for d in desc)
    cur = con.execute(f"SELECT {cols_sql} FROM {table} ORDER BY " + ("ACCOUNT_KEY" if table == "ACCOUNT_DIM" else "ACCOUNT_KEY, BILLING_CYCLE_DATE"))
    names = [d[0] for d in desc]; types = [d[1] for d in desc]
    fmts = []
    for t in types:
        if t == "DATE": fmts.append(datef)
        elif t.startswith("DECIMAL") and t.endswith(",0)") or t == "BIGINT": fmts.append(num0)
        elif t.startswith("DECIMAL(7,3)"): fmts.append(num3)
        elif t.startswith("DECIMAL"): fmts.append(num2)
        else: fmts.append(base)
    ws = wb.add_worksheet(table)
    for j, n in enumerate(names):
        ws.set_column(j, j, max(10, min(len(n) + 2, 34)), fmts[j])
        ws.write(0, j, n, head)
    r = 0
    while True:
        batch = cur.fetchmany(5000)
        if not batch: break
        for row in batch:
            r += 1
            for j, v in enumerate(row):
                if v is None: continue
                if isinstance(v, decimal.Decimal): ws.write_number(r, j, float(v), fmts[j])
                elif isinstance(v, dt.date): ws.write_datetime(r, j, dt.datetime(v.year, v.month, v.day), datef)
                elif isinstance(v, (int, float)): ws.write_number(r, j, v, fmts[j])
                else: ws.write_string(r, j, str(v), base)
    ws.freeze_panes(1, 1); ws.autofilter(0, 0, r, len(names) - 1)
    return r
n1 = dump("ACCOUNT_DIM"); n2 = dump("ACCOUNT_CYCLE_FACT")
wb.close()
print(f"Wrote {OUT}: ACCOUNT_DIM {n1:,} rows, ACCOUNT_CYCLE_FACT {n2:,} rows "
      f"({time.time() - t0:.0f} s, {Path(OUT).stat().st_size / 1e6:.1f} MB)")
